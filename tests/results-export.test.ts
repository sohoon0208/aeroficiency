import { strFromU8, unzipSync } from 'fflate';
import { describe, expect, it } from 'vitest';
import { commitAnalysisSnapshot } from '@/lib/domain/commands';
import { createDefaultProject } from '@/lib/domain/defaults';
import { createIdempotencyKey } from '@/lib/domain/ids';
import { buildFullResultsExport } from '@/lib/resultsExport/buildResultsFiles';
import { toCsv } from '@/lib/resultsExport/csv';
import { createResultsZip } from '@/lib/resultsExport/createResultsZip';
import { buildAnalysisSnapshot } from '@/lib/solver/analysis';
import type { ProjectState } from '@/lib/domain/types';

function currentBaselineState() {
  const state = createDefaultProject();
  const design = state.designs[state.activeDesignId];
  const snapshot = buildAnalysisSnapshot(state, design, 'fast');
  const transition = commitAnalysisSnapshot(state, {
    designId: design.designId,
    expectedDesignRevision: design.revision,
    expectedProjectRevision: state.projectRevision,
    expectedFlightCaseRevision: state.flightCase.revision,
    expectedConstraintsRevision: state.constraints.revision,
    idempotencyKey: createIdempotencyKey(),
    fidelity: 'fast',
  }, snapshot, 'human');
  if (!transition.result.ok) throw new Error(transition.result.error.message);
  return transition.state;
}

function diagnosticState() {
  const state = createDefaultProject();
  const design = state.designs[state.activeDesignId];
  const snapshot = buildAnalysisSnapshot(state, design, 'fast');
  snapshot.status = 'not_converged';
  state.analyses[snapshot.analysisId] = snapshot;
  return state;
}

function text(bundle: ReturnType<typeof buildFullResultsExport>, path: string) {
  const file = bundle.files.find((item) => item.path === path);
  if (!file) throw new Error(`Missing export file ${path}`);
  return file.content;
}

describe('Full Results ZIP export', () => {
  it('exports useful design inputs and status without fabricating an analysis', () => {
    const bundle = buildFullResultsExport(createDefaultProject(), '2026-09-02T12:05:00.000Z');
    expect(bundle.filename).toBe('aeroficiency-full-results-20260902T120500Z.zip');
    expect(bundle.counts).toMatchObject({ totalDesigns: 1, unanalysed: 1, detailedAnalyses: 0 });
    expect(bundle.files.map((file) => file.path)).toContain('baseline/baseline-01-00000001/design_inputs.csv');
    expect(bundle.files.map((file) => file.path)).not.toContain('baseline/baseline-01-00000001/analysis_summary.csv');
    expect(text(bundle, 'all_designs_summary.csv')).toContain('unanalysed');
    expect(text(bundle, 'baseline/baseline-01-00000001/export_status.csv')).toContain('No analysis has been run');
    expect(text(bundle, 'README.txt')).toContain('regenerated by the UI');
  });

  it('maps a current converged analysis into the requested tables and manifest', () => {
    const bundle = buildFullResultsExport(currentBaselineState(), '2026-09-02T12:05:00.000Z');
    const designRoot = 'baseline/baseline-01-00000001';
    expect(bundle.counts).toMatchObject({ currentConverged: 1, detailedAnalyses: 1 });
    for (const file of [
      'analysis_summary.csv', 'configured_checks.csv', 'convergence.csv', 'trim_spanwise_results.csv',
      'angle_sweep_results.csv', 'angle_sweep_spanwise_results.csv', 'polar_diagnostics.csv', 'warnings.csv',
    ]) expect(bundle.files.map((item) => item.path)).toContain(`${designRoot}/${file}`);
    const summary = text(bundle, `${designRoot}/analysis_summary.csv`);
    expect(summary).toContain('analysis_id,analysis_status');
    expect(summary).toContain('converged');
    const manifestText = text(bundle, 'manifest.json');
    const manifest = JSON.parse(manifestText) as { schema_version: string; files: Array<{ path: string; size_bytes: number; sha256: string | null }> };
    expect(manifest.schema_version).toBe('aeroficiency-results-export-1.0');
    expect(manifest.files.find((file) => file.path === 'manifest.json')?.size_bytes).toBe(new TextEncoder().encode(manifestText).byteLength);
    expect(manifest.files.find((file) => file.path === `${designRoot}/analysis_summary.csv`)?.sha256).toMatch(/^[a-f0-9]{64}$/);
    expect(manifest.files.some((file) => file.path.includes('activities') || file.path.includes('idempotency'))).toBe(false);
  });

  it('withholds stale numbers and exports only a diagnostic summary for a matching failed run', () => {
    const stale = currentBaselineState();
    stale.designs[stale.activeDesignId].revision += 1;
    const staleBundle = buildFullResultsExport(stale, '2026-09-02T12:05:00.000Z');
    expect(staleBundle.counts.stale).toBe(1);
    expect(staleBundle.files.map((file) => file.path)).not.toContain('baseline/baseline-01-00000001/trim_spanwise_results.csv');
    expect(text(staleBundle, 'all_designs_summary.csv')).toContain('stale');

    const diagnosticBundle = buildFullResultsExport(diagnosticState(), '2026-09-02T12:05:00.000Z');
    const diagnosticRoot = 'baseline/baseline-01-00000001';
    expect(diagnosticBundle.counts.diagnosticNotConverged).toBe(1);
    expect(diagnosticBundle.files.map((file) => file.path)).toContain(`${diagnosticRoot}/diagnostic_summary.csv`);
    expect(diagnosticBundle.files.map((file) => file.path)).not.toContain(`${diagnosticRoot}/analysis_summary.csv`);
    expect(diagnosticBundle.files.map((file) => file.path)).not.toContain(`${diagnosticRoot}/angle_sweep_spanwise_results.csv`);
    expect(text(diagnosticBundle, `${diagnosticRoot}/diagnostic_summary.csv`)).toContain('not_converged');
  });

  it('retains custom coordinate and polar inputs without exporting raw application state', () => {
    const state = createDefaultProject();
    const design = state.designs[state.activeDesignId];
    design.geometry.airfoilStations[1].airfoil = {
      kind: 'COORDINATES',
      name: 'Imported profile',
      source: 'local-test',
      points: [[1, 0], [0.5, 0.1], [0, 0], [0.5, -0.1]],
    };
    design.geometry.polarModel = {
      kind: 'USER_TABLES',
      tables: [{
        polarId: 'polar_test',
        airfoilStationId: 'afs_tip',
        reynolds: 1e6,
        mach: 0,
        rows: [{ alphaDeg: -2, cl: 0.1, cd: 0.02, cm: -0.01 }],
        provenance: { source: 'USER_IMPORT', label: 'Local polar' },
      }],
    };
    const bundle = buildFullResultsExport(state, '2026-09-02T12:05:00.000Z');
    expect(bundle.files.map((file) => file.path)).toContain('baseline/baseline-01-00000001/airfoil_coordinates.csv');
    expect(text(bundle, 'baseline/baseline-01-00000001/airfoil_coordinates.csv')).toContain('0.5,0.1');
    expect(text(bundle, 'baseline/baseline-01-00000001/polar_tables.csv')).toContain('polar_test');
    expect(bundle.files.every((file) => !file.path.includes('idempotency') && !file.path.includes('activities'))).toBe(true);
  });

  it('keeps CSV values safe, quoted, and finite', () => {
    const csv = toCsv(['label', 'number', 'multiline'], [
      { label: '=SUM(A1:A2)', number: -4, multiline: 'line 1, line 2\n"quoted"' },
      { label: '  +formula', number: Number.NaN, multiline: Number.POSITIVE_INFINITY },
    ]);
    expect(csv).toContain("'=SUM(A1:A2),-4,\"line 1, line 2\n\"\"quoted\"\"\"");
    expect(csv).toContain("  '+formula");
    expect(csv).not.toContain('NaN');
    expect(csv).not.toContain('Infinity');
  });

  it('creates an extractable ZIP while isolating the captured bundle from later state changes', async () => {
    const state: ProjectState = createDefaultProject();
    const bundle = buildFullResultsExport(state, '2026-09-02T12:05:00.000Z');
    state.designs[state.activeDesignId].label = 'Changed after export';
    expect(text(bundle, 'baseline/baseline-01-00000001/design_inputs.csv')).not.toContain('Changed after export');
    const bytes = await createResultsZip(bundle.files);
    const entries = unzipSync(bytes);
    expect(strFromU8(entries['README.txt'])).toContain('Aeroficiency Full Results export');
    expect(strFromU8(entries['manifest.json'])).toContain('aeroficiency-results-export-1.0');
    expect(Object.keys(entries)).toHaveLength(bundle.files.length);
  });

  it('rejects unsafe archive paths before compression', async () => {
    const unsafe = { path: '../outside.csv', content: 'x\n', contentType: 'text/csv' as const, sizeBytes: 2 };
    await expect(createResultsZip([unsafe])).rejects.toThrow(/unsafe file path/i);
  });
});
