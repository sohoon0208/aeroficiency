export const AIRFOIL_CATALOG_FAMILIES = [...new Set(AIRFOIL_CATALOG.map((entry) => entry.family))];

export function airfoilCatalogDefinition(id: string): AirfoilDefinition | null {
  const entry = AIRFOIL_CATALOG.find((candidate) => candidate.id === id);
  if (!entry) return null;
  return { ...entry.definition, points: entry.definition.points.map(([x, z]) => [x, z] as const) };
}

export function airfoilCatalogId(definition: AirfoilDefinition): string | null {
  if (definition.kind !== 'COORDINATES') return null;
  return AIRFOIL_CATALOG.find((entry) => entry.definition.name === definition.name && entry.definition.source === definition.source)?.id ?? null;
}
